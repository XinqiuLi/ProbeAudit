from pathlib import Path
import csv
P=Path(__file__).resolve().parent
def read(n):
 return list(csv.DictReader((P/n).open(encoding="utf-8-sig")))
rows=read("annotation_R3_input.csv")
sel={r["probe_id"]:r for r in read("selected_probes.csv")}
raw={k:{(r["probe_set"],int(r["max_mismatches"])):r for r in read(k+"_probe_summary.csv")} for k in ["historical_14","historical_ref","extension_100","extension_ref"]}
for r in rows:
 r['archived_flags_ensembl']=r['flags_ensembl'];r['archived_flags_refseq']=r['flags_refseq']
 r['eligibility_gene_biotype_ensembl116']='lncRNA' if r['probe_id'] in sel else 'historical selection; not extension eligibility'
 r['eligibility_gene_ids_ensembl116']=sel.get(r['probe_id'],{}).get('ensembl_gene_ids','')
 advice=[]
 for ref in ['ensembl','refseq']:
  key=r['sample_group'] if ref=='ensembl' else ('historical_ref' if r['sample_group']=='historical_14' else 'extension_ref')
  exact=raw[key][r['probe_id'],0]; mm=raw[key][r['probe_id'],1]
  assert int(exact['n_intended_sense'])==int(r['intended_exact_'+ref].split('/')[0])
  assert int(exact['n_offtarget_sense'])==int(r['other_gene_exact_'+ref].split('/')[0])
  represented=ref=='ensembl' or r['target_represented_refseq']=='True'
  cond={'platform_multiple_symbols':int('///' in r['previous_annotation']),
        'different_gene_exact':int(int(exact['n_offtarget_sense'])>0),
        'incomplete_intended_exact':int(int(exact['n_intended_sense'])<11),
        'different_gene_at_most_one_substitution':int(int(mm['n_offtarget_sense'])>0),
        'not_all_genomic_sites_unique':int(int(r['genome_unique_oligos'])<11)}
  for k,v in cond.items():r[k+'_'+ref]=v
  r['reference_assessable_'+ref]=int(represented)
  r['different_gene_at_most_one_substitution_oligos_'+ref]=int(mm['n_offtarget_sense'])
  r['independent_conditions_'+ref]='; '.join(k for k,v in cond.items() if v) or 'none'
  r['coverage_only_independent_'+ref]=int(represented and cond['incomplete_intended_exact'] and sum(cond.values())==1)
  r['any_condition_excluding_incomplete_'+ref]=int(represented and any(v for k,v in cond.items() if k!='incomplete_intended_exact'))
  r['coverage_only_archived_priority_flags_'+ref]=int(represented and r['flags_'+ref]=='incomplete intended-gene exact coverage')
  aliases={r['historical_candidate_label']}
  if 'LINC00152' in aliases or 'CYTOR' in aliases:aliases|={'LINC00152','CYTOR'}
  alt=sorted(set(r['exact_match_symbols_'+ref].split('|'))-aliases-{''})
  r['candidate_alternative_symbols_'+ref]='|'.join(alt)
  r['category_'+ref]=r['category_'+ref].replace('C: limited reference support','C: no flag under the retained rules')
  if not represented:advice.append('RefSeq target record absent: do not infer a gene reassignment from this gap.');continue
  nm='Ensembl' if ref=='ensembl' else 'RefSeq'
  advice.append(f"{nm}: intended exact coverage {r['intended_exact_'+ref]}; different-gene exact matches {r['other_gene_exact_'+ref]}"+(f" ({', '.join(alt)})" if alt else '')+'.')
  if cond['different_gene_exact']:advice.append('Inspect the listed alternative gene identifiers and locus overlap before exclusive target attribution; sequence compatibility does not identify the expressed source.')
  elif cond['different_gene_at_most_one_substitution']:advice.append('Inspect the additional matches allowing at most one substitution; they do not establish experimental cross-hybridization.')
  if cond['incomplete_intended_exact']:advice.append('Check transcript coverage and assay orientation before judging the intended annotation.')
 if int(r['genome_unique_oligos'])<11:advice.append(f"Genomic locations: {r['genome_unique_oligos']} unique, {r['genome_multiple_oligos']} multiple and {r['genome_no_contiguous_hit_oligos']} absent; assess locus or splice context separately.")
 if '///' in r['previous_annotation']:advice.append('Preserve every existing platform symbol; multiple labels alone do not prove multiple expressed sources.')
 if r['probe_id'] in ['207719_x_at','212746_s_at']:advice.append('CEP170 is already listed by the platform. Qualify the CEP170P1 candidate label; do not present CEP170 as a newly discovered platform assignment.')
 r['recommended_annotation']=' '.join(dict.fromkeys(advice))+' No definitive replacement is assigned; experimental specificity remains untested.'
 r['evidence_basis']='Reference-specific counts and independent conditions are reported without an evidence-strength score. Archived flags follow A-before-B priority and can omit conditions present in the underlying counts.'

with (P/"Supplementary_Annotation_Record_regenerated.csv").open("w",encoding="utf-8-sig",newline="") as f:
 w=csv.DictWriter(f,fieldnames=list(rows[0]));w.writeheader();w.writerows(rows)
assert (P/"Supplementary_Annotation_Record_regenerated.csv").read_bytes()==(P/"Supplementary_Annotation_Record.csv").read_bytes()
print("114-row annotation record regenerated byte-for-byte.")
